-- node_modules をコンテナの中だけに置く（N1〜N3）
-- 手元に node_modules が無ければ、プロジェクトごとの名前付きボリュームを重ね、手元には作らない。
-- 依存の解決はコンテナの LSP が行い、定義へ飛んだ先などのファイルはコンテナから読む。
-- 手元に node_modules があれば（手元でも開発するプロジェクト）、今までどおりそれをコンテナと共有する
local project = require("devcontainer.project")
local tools = require("devcontainer.tools")
local cli = require("devcontainer.cli")

local M = {}

local function notify(msg, level)
  vim.notify(msg, level or vim.log.levels.INFO, { title = "devcontainer" })
end

--- ボリュームを重ねる場所。ルートに package.json が無いか、手元の node_modules に中身があれば nil
--- （ボリュームを重ねたコンテナがあると、手元の node_modules はマウント先の空のディレクトリになる）
---@param p devcontainer.Project
---@return string?
function M.target(p)
  if not vim.uv.fs_stat(p.root .. "/package.json") then return end
  local dir = p.root .. "/node_modules"
  local stat = vim.uv.fs_lstat(dir)
  if stat and (stat.type ~= "directory" or vim.iter(vim.fs.dir(dir)):any(function() return true end)) then return end
  return dir
end

---@param p devcontainer.Project
function M.volume(p)
  return "nvim-devcontainer-nm-" .. vim.fn.sha256(p.root):sub(1, 16)
end

--- devcontainer.json で既に node_modules に何かマウントしているか
---@param mounts table
---@param target string
local function mounted_by_user(mounts, target)
  for _, m in ipairs(mounts) do
    if type(m) == "table" and m.target == target then return true end
    if type(m) == "string" and (("," .. m .. ","):find(",target=" .. target .. ",", 1, true)
        or ("," .. m .. ","):find(",dst=" .. target .. ",", 1, true)
        or ("," .. m .. ","):find(",destination=" .. target .. ",", 1, true)) then
      return true
    end
  end
  return false
end

--- 上書き設定にボリュームのマウントを足す（override_hooks から呼ばれる）
---@param config table
---@param p devcontainer.Project
function M.add_mount(config, p)
  local target = M.target(p)
  if not target or mounted_by_user(config.mounts, target) then return end
  table.insert(config.mounts, ("source=%s,target=%s,type=volume"):format(M.volume(p), target))
end

--- ボリュームを作り、ルートを誰でも書けるようにする（スティッキーなので他人のファイルは消せない）。
--- 新しいボリュームは root の持ち物になり、remoteUser の pnpm install が失敗するため
---@param p devcontainer.Project
---@param cb fun()
function M.prepare(p, cb)
  if not M.target(p) then return cb() end
  cli.run(p, {
    "docker", "run", "--rm", "-v", M.volume(p) .. ":/nm", tools.helper_images.glibc, "chmod", "1777", "/nm",
  }, function(line) cli.append_log(p, line) end, function(code)
    if code ~= 0 then cli.append_log(p, "node_modules のボリュームを準備できませんでした") end
    cb()
  end)
end

--- コンテナの node_modules のファイルをバッファに読み込む。手元のファイルではないので書き込めなくする
---@param p devcontainer.Project
---@param buf integer
---@param path string
local function read(p, buf, path)
  -- 依存パッケージのファイルなので、モードラインやスワップ・アンドゥのファイルを使わない
  local bo = vim.bo[buf]
  bo.swapfile, bo.undofile, bo.modeline = false, false, false
  local res = vim.system({ "docker", "exec", "-u", p.remote_user or "root", p.container_id, "cat", "--", path })
    :wait(10000)
  local lines
  if res.code == 0 then
    lines = vim.split(res.stdout or "", "\n", { plain = true })
    if lines[#lines] == "" then table.remove(lines) end
  else
    lines = {}
    notify(("コンテナから読めませんでした: %s"):format(vim.trim(res.stderr or "")), vim.log.levels.ERROR)
  end
  bo.modifiable, bo.readonly = true, false
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, lines)
  bo.modifiable, bo.readonly, bo.modified = false, true, false
  vim.api.nvim_buf_call(buf, function()
    vim.api.nvim_exec_autocmds("BufReadPost", { buffer = buf, modeline = false })
  end)
end

--- node_modules 配下のパスを開いたら、コンテナから読む
---@param p devcontainer.Project
---@param target string
local function watch(p, target)
  local group = vim.api.nvim_create_augroup("devcontainer.node_modules:" .. p.root, {})
  local pattern = vim.fn.escape(target, "\\*?[]{},") .. "/*"
  vim.api.nvim_create_autocmd("BufReadCmd", {
    group = group,
    pattern = pattern,
    nested = true,
    callback = function(ev)
      local path = vim.api.nvim_buf_get_name(ev.buf)
      if p.status == "ready" then return read(p, ev.buf, path) end
      notify("コンテナが起動していないので、node_modules のファイルは読めません", vim.log.levels.WARN)
    end,
  })
  vim.api.nvim_create_autocmd({ "BufWriteCmd", "FileWriteCmd", "FileAppendCmd" }, {
    group = group,
    pattern = pattern,
    callback = function()
      notify("node_modules はコンテナの中にあるので、手元からは書き込めません", vim.log.levels.ERROR)
    end,
  })
end

--- コンテナの準備ができたとき。node_modules にボリュームが重なっていれば（cli.up で調べてある）、
--- その配下のファイルをコンテナから読むようにする
---@param p devcontainer.Project
function M.on_ready(p)
  vim.api.nvim_create_augroup("devcontainer.node_modules:" .. p.root, {})
  if p.node_modules_volume then watch(p, p.root .. "/node_modules") end
end

local lockfiles = { "pnpm-lock.yaml", "package-lock.json", "yarn.lock", "bun.lock", "bun.lockb" }

--- 依存が入れ直されたら探し直せるよう、ロックファイルの更新時刻をキーに含める
---@param dir string
local function lock_mtime(dir)
  for _, name in ipairs(lockfiles) do
    local stat = vim.uv.fs_stat(dir .. "/" .. name)
    if stat then return stat.mtime.sec .. "." .. stat.mtime.nsec end
  end
  return ""
end

local resolve_script = [[
r=$1; shift
for n; do
  b="$r/node_modules/.bin/$n"
  if [ -e "$b" ]; then echo "$n=$b"; continue; fi
  v=$(readlink -f "$r/node_modules/vite-plus" 2>/dev/null) || continue
  b="${v%/*}/$n/bin/$n"
  [ -e "$b" ] && echo "$n=$b"
done
[ -d "$r/node_modules/typescript/lib" ] && echo "typescript=$r/node_modules/typescript/lib"
exit 0
]]

--- コンテナの中で、プロジェクトの node_modules にあるコマンドと TypeScript を探す（lsp.project_bin と同じ探し方）。
--- 手元には node_modules が無いので、コンテナで探す。結果はプロジェクトごとに覚え、
--- 未確認なら確認を始めて nil を返す（終わったら on_done を呼ぶ）
---@param p devcontainer.Project
---@param dir string
---@param names string[]
---@param on_done fun()
---@return table<string, string>?
function M.resolve(p, dir, names, on_done)
  p.resolved = p.resolved or {}
  local key = dir .. "\0" .. lock_mtime(dir) .. "\0" .. lock_mtime(p.root)
  local cached = p.resolved[key]
  if cached == "checking" then return nil end
  if cached then return cached end
  p.resolved[key] = "checking"
  local cmd = { "sh", "-c", resolve_script, "sh", dir }
  tools.exec(p, p.remote_user or "root", vim.list_extend(cmd, names), function(code, out)
    local found = {}
    if code == 0 then
      for line in out:gmatch("[^\n]+") do
        local k, v = line:match("^([^=]+)=(.+)$")
        if k then found[k] = v end
      end
    end
    p.resolved[key] = found
    on_done()
  end)
end

return M
